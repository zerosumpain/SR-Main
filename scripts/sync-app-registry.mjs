#!/usr/bin/env node
/**
 * Vendor SR-Infra's application registry into this repo.
 *
 * `~/sr-infra/registry/apps.json` is the authoritative description of the
 * estate: every extracted application with its repo, its status, its gateway /
 * primary / candidate / worker ports, the paths cloudflared routes to it, the
 * patterns that pass through unsigned, and the queue triggers its worker claims.
 * `scripts/generate-ingress.mjs` in that repo builds the live cloudflared config
 * from it, so it is not documentation — it is what is running.
 *
 * SR-Main had never read it. It carried `src/lib/architecture/topology.ts`
 * instead: 16 hand-written nodes that knew about none of the six extracted apps,
 * and `docs/module-ownership.json`, which was four apps behind.
 *
 * Why vendor rather than read it at request time:
 *  - SR-Infra is a separate repository that exists on homeserv and nowhere else.
 *    CI runs on a GitHub-hosted runner and the VPS has no checkout of it.
 *  - `src/` is not deployed (see vite-plugins/route-manifest.mjs), so a runtime
 *    filesystem read on the VPS reads a stale leftover, succeeds, and lies.
 *  - A committed generated file travels inside the build that serves it, which
 *    is the same doctrine the route manifest already follows.
 *
 * The cost of vendoring is staleness, and the honest answer to that is not to
 * pretend otherwise: `scripts/check-app-registry.mjs` fails the gate when this
 * file drifts from source (on a host that has SR-Infra) or ages past the
 * tolerance (everywhere else), and the estate model renders the stamp so the
 * page says how old its own answer is.
 *
 * Usage:  node scripts/sync-app-registry.mjs [--check]
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';

const SOURCE_DIR = process.env.SR_INFRA_DIR || join(homedir(), 'sr-infra', 'registry');
const OUT = join(process.cwd(), 'src', 'lib', 'estate', 'registry', 'apps.generated.json');
const CHECK = process.argv.includes('--check');

/** The fields the estate model consumes. Anything else in the source is ignored
 *  deliberately, so an unrelated addition upstream does not churn this file. */
function projectApp(key, a, ops) {
  return {
    key,
    repo: a.repo ?? null,
    status: a.status ?? 'unknown',
    audience: a.audience ?? null,
    releaseDir: a.releaseDir ?? null,
    configDir: a.configDir ?? null,
    assetPrefix: a.assetPrefix ?? null,
    ports: a.ports ?? {},
    paths: a.paths ?? [],
    excludePaths: a.excludePaths ?? [],
    publicPatterns: a.publicPatterns ?? [],
    // Normalised: the source allows a bare string OR {pattern, methods}.
    passthroughPatterns: (a.passthroughPatterns ?? []).map((p) =>
      typeof p === 'string' ? { pattern: p, methods: null } : { pattern: p.pattern, methods: p.methods ?? null },
    ),
    queueTriggers: a.queueTriggers ?? [],
    note: a.note ?? null,
    // From operations.json, keyed by the same app key.
    branch: ops?.branch ?? null,
    workflows: ops?.workflows ?? [],
    executionOwner: ops?.executionOwner ?? null,
    migrationAuthor: ops?.migrationAuthor ?? null,
    schemaExecutor: ops?.schemaExecutor ?? null,
  };
}

function build() {
  const apps = JSON.parse(readFileSync(join(SOURCE_DIR, 'apps.json'), 'utf8'));
  let operations = { applications: {} };
  const opsPath = join(SOURCE_DIR, 'operations.json');
  if (existsSync(opsPath)) operations = JSON.parse(readFileSync(opsPath, 'utf8'));

  const ops = operations.applications ?? {};
  return {
    $comment:
      'GENERATED by scripts/sync-app-registry.mjs from ~/sr-infra/registry/. Do not hand-edit — ' +
      'change the source registry and re-run. scripts/check-app-registry.mjs fails the gate on drift.',
    source: 'zerosumpain/SR-Infra registry/apps.json + operations.json',
    syncedAt: new Date().toISOString().slice(0, 10),
    canonicalHost: apps.canonicalHost ?? null,
    mainOrigin: apps.mainOrigin ?? null,
    // cloudflared is FIRST-MATCH, so this order is behaviour, not presentation:
    // `main` is last as the deliberate fallback that keeps a half-finished
    // extraction safe. Any claim the estate page makes about who can reach what
    // has to respect it.
    routeOrder: apps.routeOrder ?? [],
    apps: Object.entries(apps.apps ?? {}).map(([k, a]) => projectApp(k, a, ops[k])),
  };
}

if (!existsSync(join(SOURCE_DIR, 'apps.json'))) {
  console.error(
    `sync-app-registry: no registry at ${SOURCE_DIR}.\n` +
      'This script only runs on a host with an SR-Infra checkout (homeserv). ' +
      'Everywhere else the committed src/lib/estate/registry/apps.generated.json is the input.',
  );
  process.exit(CHECK ? 0 : 1);
}

const next = build();
const prev = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : null;

// syncedAt is excluded from the comparison: re-running on a day when nothing
// changed must not produce a diff, or the gate cries wolf every morning.
const same = prev && JSON.stringify({ ...prev, syncedAt: '' }) === JSON.stringify({ ...next, syncedAt: '' });

if (CHECK) {
  if (same) {
    console.log(`check-app-registry: OK — ${next.apps.length} apps, in step with ${SOURCE_DIR}.`);
    process.exit(0);
  }
  console.error(
    'check-app-registry: the vendored registry has DRIFTED from SR-Infra.\n' +
      '  Run: node scripts/sync-app-registry.mjs   then commit the result.',
  );
  process.exit(1);
}

writeFileSync(OUT, `${JSON.stringify(next, null, 2)}\n`);
console.log(
  `sync-app-registry: wrote ${next.apps.length} apps to src/lib/estate/registry/apps.generated.json` +
    (same ? ' (content unchanged)' : ''),
);
