#!/usr/bin/env node
// Writes src/lib/games/hometowns/page-hash.generated.ts: PAGE_HASH, an FNV-1a
// 64 over ENGINE_HASH and every file the map page's build reads (spec §10.10).
// The page is deployed under /projects/hometowns/<PAGE_HASH>/ and the wire
// names that path, so a page-only change (a drawing fix, say) gets a folder of
// its own and every published folder stays exactly as it was.
//
// ENGINE_HASH keeps its meaning, "the same simulation": the canary and the
// predictor compare it. PAGE_HASH is "the same page": it changes whenever
// ENGINE_HASH does, and also when only the page changes. It lives outside
// engine/ so the server can name it without importing page code, and so a
// page change never touches an engine file.
//
//   node scripts/hometowns/page-hash.mjs           # rewrite the file
//   node scripts/hometowns/page-hash.mjs --check   # exit 1 if it is stale
//
// page-hash.test.ts runs the same computation, so a stale hash fails the gate:
// rerun engine-hash.mjs (after an engine change) and then this script after
// any engine or page change.

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { computeEngineHash } from './engine-hash.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const REPO = resolve(HERE, '../..');
export const VIEW = 'games/hometowns-view';
export const GENERATED_PAGE = 'src/lib/games/hometowns/page-hash.generated.ts';

/**
 * What `vite build` reads besides the engine (which ENGINE_HASH covers): the
 * engine folders ENGINE_HASH skips but the page bundles (below), the
 * page's sources and HTML, its build config, the lockfile that pins its
 * node_modules and a public/ folder if one is ever added. vite.config.ts fixes
 * the TypeScript transform's options itself (esbuild.tsconfigRaw), so no
 * tsconfig.json outside this package, the repository's or SvelteKit's
 * generated one, reaches the bundle; the page's own tsconfig.json is hashed
 * anyway, as it sets the same options for `npm run check`. Files that do not
 * exist are skipped. Tests, e2e, README and .npmrc are not build input.
 */
const PAGE_FILES = [`${VIEW}/index.html`, `${VIEW}/package.json`, `${VIEW}/package-lock.json`, `${VIEW}/tsconfig.json`, `${VIEW}/vite.config.ts`];
const PAGE_DIRS = [`${VIEW}/src`, `${VIEW}/public`];
/**
 * Engine folders ENGINE_HASH leaves out (engine-hash.mjs NOT_ENGINE) that the
 * page still bundles: the harness's `bot=1` plays the Lab's Balanced bot from
 * engine/bots. A bot change is not a simulation change, but it is a page
 * change, so it must give a new folder. Their tests are not build input.
 */
const ENGINE_PAGE_DIRS = ['src/lib/games/hometowns/engine/bots'];

/** The page's build inputs, repository-relative and sorted (dot-files and dot-folders skipped). */
export function pageFiles(root = REPO) {
  const out = PAGE_FILES.filter((f) => existsSync(join(root, f)));
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      if (name.startsWith('.')) continue;
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(root, p).split('\\').join('/'));
    }
  };
  for (const d of PAGE_DIRS) if (existsSync(join(root, d))) walk(join(root, d));
  const before = out.length;
  for (const d of ENGINE_PAGE_DIRS) if (existsSync(join(root, d))) walk(join(root, d));
  out.splice(before, out.length - before, ...out.slice(before).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts')));
  return [...new Set(out)].sort();
}

function fnv64(bytes, h = 0xcbf29ce484222325n) {
  const prime = 0x100000001b3n;
  const mask = 0xffffffffffffffffn;
  for (const b of bytes) h = ((h ^ BigInt(b)) * prime) & mask;
  return h;
}

/** PAGE_HASH for the tree at `root`: ENGINE_HASH (recomputed from its engine/), then each page file's path and bytes. */
export function computePageHash(root = REPO) {
  const enc = new TextEncoder();
  const engine = computeEngineHash(join(root, 'src/lib/games/hometowns/engine'));
  let h = fnv64(enc.encode(`engine\0${engine}\0`));
  for (const rel of pageFiles(root)) {
    h = fnv64(enc.encode(rel + '\0'), h);
    h = fnv64(readFileSync(join(root, rel)), h);
    h = fnv64(enc.encode('\0'), h);
  }
  return h.toString(16).padStart(16, '0');
}

export function generatedPageSource(hash) {
  return `// GENERATED by scripts/hometowns/page-hash.mjs: do not edit. Rerun it after any engine or page change.\nexport const PAGE_HASH = '${hash}';\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const hash = computePageHash();
  const target = join(REPO, GENERATED_PAGE);
  const want = generatedPageSource(hash);
  let have = '';
  try {
    have = readFileSync(target, 'utf8');
  } catch {}
  if (process.argv.includes('--check')) {
    if (have !== want) {
      console.error(`PAGE_HASH is stale (want ${hash}); run node scripts/hometowns/page-hash.mjs`);
      process.exit(1);
    }
    console.log(`PAGE_HASH ${hash} is current`);
  } else {
    writeFileSync(target, want);
    console.log(`PAGE_HASH ${hash}`);
  }
}
