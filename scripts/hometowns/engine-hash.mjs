#!/usr/bin/env node
// Writes src/lib/games/hometowns/engine/engine-hash.generated.ts: ENGINE_HASH,
// an FNV-1a 64 over every engine source and params file (spec §10.1, §10.10).
// It means "the same simulation": the wire names it beside the page, and the
// page's canary and predictor compare it. The page's folder is PAGE_HASH,
// which covers ENGINE_HASH and the page code (page-hash.mjs): rerun that
// script after this one.
//
//   node scripts/hometowns/engine-hash.mjs           # rewrite the file
//   node scripts/hometowns/engine-hash.mjs --check   # exit 1 if it is stale
//
// engine.test.ts runs the same computation, so a stale hash fails the gate:
// rerun this script after any engine change.

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const ENGINE_DIR = resolve(HERE, '../../src/lib/games/hometowns/engine');
export const GENERATED = 'engine-hash.generated.ts';

/**
 * Folders under engine/ that are not the engine a phone runs: the Lab's bot
 * mayors (tuning a bot must not redeploy the page), and anything a tool
 * generates or hides (dot-folders such as a stray .svelte-kit).
 */
const NOT_ENGINE = new Set(['bots']);

/** Engine files that define behaviour: .ts and .json, not tests, not the generated file. */
export function engineFiles(dir = ENGINE_DIR) {
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) {
        if (d === dir && NOT_ENGINE.has(name)) continue;
        if (!name.startsWith('.')) walk(p);
      } else if ((name.endsWith('.ts') || name.endsWith('.json')) && !name.endsWith('.test.ts') && name !== GENERATED) out.push(p);
    }
  };
  walk(dir);
  return out.map((p) => relative(dir, p).split('\\').join('/')).sort();
}

function fnv64(bytes, h = 0xcbf29ce484222325n) {
  const prime = 0x100000001b3n;
  const mask = 0xffffffffffffffffn;
  for (const b of bytes) h = ((h ^ BigInt(b)) * prime) & mask;
  return h;
}

export function computeEngineHash(dir = ENGINE_DIR) {
  let h = 0xcbf29ce484222325n;
  const enc = new TextEncoder();
  for (const rel of engineFiles(dir)) {
    h = fnv64(enc.encode(rel + '\0'), h);
    h = fnv64(readFileSync(join(dir, rel)), h);
    h = fnv64(enc.encode('\0'), h);
  }
  return h.toString(16).padStart(16, '0');
}

export function generatedSource(hash) {
  return `// GENERATED by scripts/hometowns/engine-hash.mjs: do not edit. Rerun it after any engine change.\nexport const ENGINE_HASH = '${hash}';\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const hash = computeEngineHash();
  const target = join(ENGINE_DIR, GENERATED);
  const want = generatedSource(hash);
  let have = '';
  try {
    have = readFileSync(target, 'utf8');
  } catch {}
  if (process.argv.includes('--check')) {
    if (have !== want) {
      console.error(`ENGINE_HASH is stale (want ${hash}); run node scripts/hometowns/engine-hash.mjs`);
      process.exit(1);
    }
    console.log(`ENGINE_HASH ${hash} is current`);
  } else {
    writeFileSync(target, want);
    console.log(`ENGINE_HASH ${hash}`);
  }
}
