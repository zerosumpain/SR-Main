import fs from 'node:fs';
import ts from 'typescript';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const main = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const owner = process.argv[2];
if (!owner) throw new Error('Usage: node scripts/sync-workflow-tool-descriptors.mjs /path/to/SR-Workflows');
const parse = (path) => {
 const text = fs.readFileSync(`${owner}/${path}`, 'utf8');
 return ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
};
// Descriptions share two prose constants with SR-Workflows. Main no longer
// carries the expression engine or the amend validator they live beside, so
// their declarations are copied into the generated file verbatim.
const constant = (path, name) => {
 const file = parse(path);
 for (const node of file.statements) {
  if (!ts.isVariableStatement(node)) continue;
  const decl = node.declarationList.declarations.find((d) => d.name.getText(file) === name);
  if (decl?.initializer) return `const ${name} =\n  ${decl.initializer.getText(file)};`;
 }
 throw new Error(`${name} not found in ${path}`);
};
const ast = parse('src/lib/workflows/site-tools/tools/workflows.ts');
let chunks=[];
for(const node of ast.statements){
 if(!ts.isExpressionStatement(node)||!ts.isCallExpression(node.expression)||node.expression.expression.getText(ast)!=='register')continue;
 const arg=node.expression.arguments[0];
 const props=arg.properties.filter(p=>p.name?.getText(ast)!=='handler').map(p=>p.getText(ast));
 chunks.push(`registerWorkflowTool({\n  ${props.join(',\n  ')}\n});`);
}
const constants = [
 constant('src/lib/workflows/expressions.ts', 'EXPRESSION_SYNTAX'),
 constant('src/lib/canvas/amend-validate.server.ts', 'AMEND_OPS_DESCRIPTION'),
].join('\n\n');
const code=`// Generated by scripts/sync-workflow-tool-descriptors.mjs from SR-Workflows; do not edit handlers here.\nimport { registerWorkflowTool } from '../workflow-service';\n\n${constants}\n\n${chunks.join('\n\n')}\n`;
fs.writeFileSync(`${main}/src/lib/tools/tools/workflows.ts`,code);
console.log(`${chunks.length} tool descriptors retained`);
