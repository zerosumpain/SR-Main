import fs from 'node:fs';
import ts from 'typescript';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const main = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const owner = process.argv[2];
if (!owner) throw new Error('Usage: node scripts/sync-workflow-tool-descriptors.mjs /path/to/SR-Workflows');
const src=fs.readFileSync(`${owner}/src/lib/workflows/site-tools/tools/workflows.ts`,'utf8');
const ast=ts.createSourceFile('tools.ts',src,ts.ScriptTarget.Latest,true);
let chunks=[];
for(const node of ast.statements){
 if(!ts.isExpressionStatement(node)||!ts.isCallExpression(node.expression)||node.expression.expression.getText(ast)!=='register')continue;
 const arg=node.expression.arguments[0];
 const props=arg.properties.filter(p=>p.name?.getText(ast)!=='handler').map(p=>p.getText(ast));
 chunks.push(`registerWorkflowTool({\n  ${props.join(',\n  ')}\n});`);
}
const code=`// Generated by scripts/sync-workflow-tool-descriptors.mjs from SR-Workflows; do not edit handlers here.\nimport { EXPRESSION_SYNTAX } from '$lib/workflows/expressions';\nimport { AMEND_OPS_DESCRIPTION } from '$lib/canvas/amend-validate.server';\nimport { registerWorkflowTool } from '../workflow-service';\n\n${chunks.join('\n\n')}\n`;
fs.writeFileSync(`${main}/src/lib/workflows/site-tools/tools/workflows.ts`,code);
console.log(`${chunks.length} tool descriptors retained`);
