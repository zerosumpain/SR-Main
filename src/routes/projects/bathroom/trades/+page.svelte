      <table>
        <thead>
          <tr><th>Trade</th><th>On your job</th><th>Days</th><th>Day rate (NE)</th><th>What they must leave you</th></tr>
        </thead>
        <tbody>
          <tr>
            <td><strong>Bathroom fitter</strong></td>
            <td>The all-rounder. Strip out, plumbing, fitting, usually tiling, usually the boxing and boarding. Often runs the whole job.</td>
