      <hr class="bth-rule" />
    </div>
    <div class="bth-tablewrap">
      <table>
        <thead><tr><th>Job</th><th>Saves</th><th>Verdict</th></tr></thead>
        <tbody>
          <tr><td>Buying the suite, tiles and brassware yourself</td><td class="n">£200–£800</td><td><span class="bth-pill good">Do it</span> As long as you order early and check every box on arrival. Ask the fitter for his exact spec list first.</td></tr>
          <tr><td>Stripping out the old bathroom</td><td class="n">£250–£450</td><td><span class="bth-pill good">Do it</span> A weekend, a crowbar and a skip. Cap the pipes off, or leave the last bit for the fitter. Genuinely satisfying.</td></tr>
          <tr><td>Painting the ceiling and any bare walls</td><td class="n">£150–£400</td><td><span class="bth-pill good">Do it</span> Once everything's dry. Use a proper bathroom paint.</td></tr>
          <tr><td>Taking the rubbish away</td><td class="n">£150–£300</td><td><span class="bth-pill warn">Maybe</span> Depends whether you fancy several trips to the tip with a bath in the car.</td></tr>
          <tr><td>Tiling</td><td class="n">£600–£1,400</td><td><span class="bth-pill warn">Only if you've done it</span> The setting-out is the skill, not the sticking-on. A first attempt in a small room with lots of cuts is a hard first attempt.</td></tr>
          <tr><td>Plumbing</td><td class="n">£600–£1,200</td><td><span class="bth-pill crit">No</span> Legal, but a leak behind a tiled wall costs more than the saving, twice over.</td></tr>
          <tr><td>Electrics</td><td class="n">£350–£900</td><td><span class="bth-pill crit">No</span> Notifiable work in a bathroom. Without the certificate you'll have problems with insurance and with any future sale.</td></tr>
        </tbody>
      </table>
    </div>
    <div class="bth-note warn">
      <span class="bth-eyebrow">The catch with splitting the work</span>
      <p class="bth-small">
        The moment you supply the materials, you own the materials risk. If the bath arrives chipped
        on day one, that's your problem to solve while five trades stand about. Order two weeks
        early, unbox everything, and check it. Same with doing the strip-out: if you uncover
        something horrible, that's now on your critical path.
      </p>
    </div>
