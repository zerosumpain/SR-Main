  <section class="bth-stack g24">
    <div class="bth-stack g8">
      <span class="bth-eyebrow">Picking the person</span>
      <h2 class="bth-h2">How to vet a fitter in twenty minutes</h2>
      <hr class="bth-rule" />
    </div>
    <div class="bth-grid two">
      <div class="bth-stack g16">
        <h3 class="bth-h3">Where to find three</h3>
        <ul class="bth-ticks">
          <li><strong>Ask the street.</strong> On a terrace, someone within fifty metres has had a bathroom done in the last three years. Best lead you'll get.</li>
          <li><strong>Checkatrade, MyBuilder, Rated People.</strong> Vetted, reviewed, and they'll hand you several local names in a day.</li>
          <li><strong>TrustMark</strong> is the government-endorsed scheme — worth filtering on.</li>
          <li><strong>Which? Trusted Traders</strong> if you want an extra layer of checking.</li>
          <li><strong>A showroom's own installer list</strong> if you're going Route A.</li>
        </ul>
        <h3 class="bth-h3">What to check</h3>
        <ul class="bth-ticks">
          <li>Public liability insurance, at least £2m, and see the certificate.</li>
          <li>The electrician's Part P scheme membership — NICEIC, NAPIT or ELECSA — and the registration number, which you can verify online in a minute.</li>
          <li>Gas Safe number if a boiler is involved. Also verifiable online.</li>
          <li>Whether they're VAT registered, so you're comparing quotes properly.</li>
          <li>A job they finished at least two years ago, not just last month's. Anyone can make a bathroom look good in week one.</li>
        </ul>
      </div>
      <div class="bth-stack g16">
        <div class="bth-card">
          <h3 class="bth-h3">Ask every one of them these</h3>
          <ol class="bth-ol">
            <li>Who's actually on site each day — you, or someone else?</li>
            <li>How many days, and are they consecutive?</li>
            <li>What's in the price and what isn't? Skip, waste, making good, decorating?</li>
            <li>Do you supply the materials or do we?</li>
            <li>Who provides the electrical certificate?</li>
            <li>What happens if you find something behind the wall — how do you price it?</li>
            <li>What's your payment schedule?</li>
            <li>What's your guarantee, and is it insurance-backed or just your word?</li>
            <li>Can we speak to the last two customers?</li>
          </ol>
        </div>
        <div class="bth-note crit">
          <span class="bth-eyebrow">Walk away if</span>
          <ul class="bth-ticks">
            <li>They want more than 25% up front, or want cash for the deposit.</li>
            <li>They can start tomorrow. Good fitters are booked weeks out.</li>
            <li>They won't put a fixed price in writing.</li>
            <li>The quote is one line and a number.</li>
            <li>They're vague about who does the electrics, or say a certificate "isn't needed for this".</li>
            <li>They knocked on your door.</li>
          </ul>
        </div>
      </div>
