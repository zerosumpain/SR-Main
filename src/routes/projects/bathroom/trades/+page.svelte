          <dt>County Durham Bathrooms</dt>
          <dd>Local design-supply-install outfit covering Darlington. Does video-call quotes, which is a quick way to get a ballpark without an appointment.</dd>
          <dt>Wickes</dt>
          <dd>Design service plus approved local installers, technical survey before you commit, and interest-free credit at the bigger spends. Predictable rather than exciting.</dd>
          <dt>Inspira Bathrooms — Durham</dt>
          <dd>Half an hour up the road. Worth it if you want a more designed feel and a home consultation.</dd>
        </dl>
      </div>
      <div class="bth-card">
        <span class="bth-eyebrow">Online, for price</span>
        <dl class="bth-defs">
          <dt>Victorian Plumbing / Victoria Plum</dt>
          <dd>The big two online. Enormous range, aggressive sale pricing, free design service, 0% finance. Order early — returns and replacements take days you won't have.</dd>
          <dt>Bathrooms.com / Better Bathrooms</dt>
          <dd>Mid-market with showrooms in the region, so you can see it and then buy it.</dd>
          <dt>Tile specialists</dt>
          <dd>Buy tiles from a tile merchant, not a general retailer. Better rectification (edges cut square), better advice on adhesive, and they'll take unopened boxes back.</dd>
