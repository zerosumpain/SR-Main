  <header class="bth-stack g12">
    <span class="bth-eyebrow">05 · Who does what</span>
    <h1 class="bth-h1">Three ways to get this built</h1>
    <p class="bth-lead">
      A bathroom needs five trades and about forty deliveries to arrive in the right order. Somebody
      has to hold that. The only real question is whether you pay someone to do it or do it
      yourself — and the honest answer is that the middle option suits most people.
    </p>
  </header>

  <div class="bth-grid three">
    <article class="bth-card">
      <div class="bth-row" style="justify-content:space-between; align-items:flex-start">
        <div class="bth-stack g8">
          <span class="bth-eyebrow" style="color:var(--accent)">Route A</span>
          <h2 class="bth-h3">One firm, end to end</h2>
        </div>
        <span class="bth-pill">+15–30%</span>
      </div>
      <p class="bth-small">
        A showroom or bathroom company designs it, supplies everything and installs it with their
        own or approved fitters. One contract, one number to ring, one guarantee.
      </p>
      <dl class="bth-defs">
        <dt>You get</dt><dd>3D design, a fixed price, project management, insurance-backed warranty, usually finance.</dd>
        <dt>You pay</dt><dd>A premium on the materials, and you're limited to what they stock.</dd>
        <dt>Watch for</dt><dd>Subcontracted fitters you never met until day one. Ask to meet the actual installer before you sign.</dd>
        <dt>Suits</dt><dd>Not much spare time, want someone accountable, happy to pay for calm.</dd>
      </dl>
    </article>

    <article class="bth-card accent">
      <div class="bth-row" style="justify-content:space-between; align-items:flex-start">
        <div class="bth-stack g8">
          <span class="bth-eyebrow" style="color:var(--accent)">Route B</span>
          <h2 class="bth-h3">A fitter who brings his own trades</h2>
        </div>
        <span class="bth-pill accent">Most people</span>
      </div>
      <p class="bth-small">
        An experienced bathroom fitter does the plumbing, tiling and fitting himself and brings in an
        electrician and a plasterer he's worked with for years. You buy the suite, tiles and
        brassware — often through his trade account at a discount.
      </p>
      <dl class="bth-defs">
        <dt>You get</dt><dd>Showroom-quality work at 15–30% less, and total freedom on what you buy.</dd>
        <dt>You pay</dt><dd>With attention: you order the materials and you check them in.</dd>
        <dt>Watch for</dt><dd>Make sure his electrician is Part P registered and the certificate is in the price.</dd>
        <dt>Suits</dt><dd>Almost everyone. This is the sweet spot for a job this size.</dd>
      </dl>
    </article>

    <article class="bth-card">
      <div class="bth-row" style="justify-content:space-between; align-items:flex-start">
        <div class="bth-stack g8">
          <span class="bth-eyebrow" style="color:var(--accent)">Route C</span>
          <h2 class="bth-h3">You run it</h2>
        </div>
        <span class="bth-pill">−10–20%</span>
      </div>
      <p class="bth-small">
        You book each trade individually, sequence them yourself, buy everything and take the risk
        when day four's plasterer doesn't turn up and day five's tiler is already booked elsewhere.
      </p>
      <dl class="bth-defs">
        <dt>You get</dt><dd>The lowest cash cost and complete control.</dd>
        <dt>You pay</dt><dd>Roughly 20–40 hours of your time, and you own every gap in the programme.</dd>
        <dt>Watch for</dt><dd>Nobody's responsible for the whole. If the tiling cracks, the tiler blames the floor and the joiner blames the tiler.</dd>
        <dt>Suits</dt><dd>You've done it before, or you're doing some of the work yourself anyway.</dd>
      </dl>
    </article>
  </div>

