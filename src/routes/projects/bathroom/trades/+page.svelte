            <td>Fan, lights, shaver socket, towel rail spur, underfloor heating circuit, RCD protection. Legally notifiable work.</td>
            <td class="n">1–2</td><td class="n">£250–£400</td>
            <td><strong>An Electrical Installation Certificate or Minor Works Certificate, and Part P notification.</strong> Non-negotiable.</td>
          </tr>
          <tr>
            <td><strong>Tiler</strong></td>
            <td>Setting out, cutting, fixing, grouting, trims. The trade whose quality you'll notice most.</td>
            <td class="n">2–4</td><td class="n">£200–£300 or £40–£60/m²</td>
            <td>Spare tiles, and the grout and adhesive brand in writing.</td>
          </tr>
          <tr>
            <td><strong>Plasterer</strong></td>
            <td>Boarding, skimming the ceiling and any untiled walls, making good after first fix.</td>
            <td class="n">1–2</td><td class="n">£150–£250</td>
            <td>Nothing formal. Needs drying time before anyone paints or tiles.</td>
          </tr>
          <tr>
            <td><strong>Joiner</strong></td>
            <td>Floor repairs and overlay, boxing in pipework, a new door or architrave, fitted furniture.</td>
            <td class="n">1–2</td><td class="n">£180–£280</td>
            <td>Nothing formal.</td>
          </tr>
          <tr>
            <td><strong>Decorator</strong></td>
            <td>The ceiling and any painted walls. Often the fitter does it, sometimes badly.</td>
            <td class="n">1</td><td class="n">£150–£220</td>
            <td>Paint tins and colour codes for touching up.</td>
          </tr>
          <tr>
            <td><strong>Gas engineer</strong></td>
            <td>Only if the boiler is moved, replaced or the system is changed. Must be Gas Safe registered.</td>
            <td class="n">—</td><td class="n">£250–£450</td>
            <td>Gas Safe certificate and registration number you can check online.</td>
          </tr>
        </tbody>
