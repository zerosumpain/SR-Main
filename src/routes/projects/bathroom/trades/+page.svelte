      <hr class="bth-rule" />
    </div>
    <p class="bth-body" style="max-width:68ch">
      Worth walking into two showrooms before buying anything online — you cannot tell the weight of
      a tap or the depth of a bath from a photograph. The named places below are North East ones;
      the pattern is the same wherever you are. Check current addresses and opening hours before you
      set off.
    </p>
    <div class="bth-grid two">
