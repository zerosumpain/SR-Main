  <h2 class="pe-h2">Replace the engine, keep the dashboard</h2>
  <p class="pe-prose cols">
    <span>The site originally ran its own reasoning loop in-process. It had to re-implement tool orchestration,
      memory, skills, sub-agent delegation and session state — all of it work that a dedicated agent runtime already
      does properly. So the chat was cut over to one.</span>
    <span>The non-obvious part is that the cutover was made <b>invisible to the interface</b>. Rather than rewrite the
      browser client to speak the runtime's native protocol, the server translates its outbound frames into the event
      vocabulary the existing chat already consumed. Fourteen frame kinds in; twenty event variants out.</span>
    <span>The payoff is that both engines can drive the same interface and the switch is a flag. The old loop is
      still on disk, dormant, roughly eleven hundred lines of it — kept precisely because a rollback that requires a
      rewrite is not a rollback.</span>
    <span>The price is that the site can no longer instrument the model call directly. Cost, throughput and liveness
      all have to be reconstructed from the outside, from a stream of frames, which is why so much of this section is
      about a stream of frames.</span>
  </p>

  <h2 class="pe-h2">One answer, several messages</h2>
  <p class="pe-prose" style="max-width:82ch">
    {#if eli}
      The reply does not arrive in one piece. It comes in chunks, and mixed in with those chunks are the system's own
      "still working" notes — travelling down exactly the same wire. Tell them apart wrongly and a progress note can
      wipe out the answer. That is not hypothetical: it happened.
    {:else}
      The runtime opens a fresh message id at every tool boundary, so one reply arrives as a chain of segments. It
      also interleaves its own status bubbles on the same text channel, re-editing them in place. Step the real
      sequence through both accumulators and watch what a flat one does.
    {/if}
  </p>

