  <div class="er-lesson">
    <span class="el-lab">The best kind of bug — the fix that broke something else</span>
    <p>Routing the progress filler off the text channel was correct, and it immediately created a second fault. The
      four-minute idle watchdog had been getting reset, <b>entirely by accident</b>, by that periodic filler arriving.
      Nobody designed it as a liveness signal; it just happened to be one. Remove it and any genuinely silent
      stretch — a rate-limit backoff, a long provider prefill — now trips a watchdog that used to be quietly held open.</p>
    <p>This is an <b>accidental invariant</b>: behaviour the system depended on that nothing declared and no test
      covered. They are only discoverable by breaking them, which is a good argument for fixing one thing at a time
      and watching what else moves.</p>
