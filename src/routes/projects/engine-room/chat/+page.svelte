      <span class="ds-kicker">Reconnection</span>
      <h3>Resume, never replay</h3>
      <p class="ds-body">Consumers <b>append</b> deltas. So replaying a job's buffer after a dropped connection
        silently doubled the reply — and invisibly, because the server accumulates separately, which is exactly why
        "a reload fixes it" was such a misleading symptom. Every published frame now carries its buffer index as the
        stream's event id, so the browser's native resume header picks up precisely where it stopped. That is what
        makes a twelve-second gap detector safe to run at all.</p>
    </div>
    <div class="ds-card">
      <span class="ds-kicker">The throughput meter</span>
      <h3>Measuring the wait, not just the typing</h3>
      <p class="ds-body">Most tokens-per-second readouts measure only the pleasant part. This one counts reply
        tokens, reasoning deltas and the arguments the model generated for its tool calls — and deliberately includes
        the waiting. Whole-bubble swaps are excluded because they would double-count; sub-agent frames are excluded
        because a delegate runs inside a parent that is already paused. The result is a materially lower number on
        tool-heavy turns, which is the honest one.</p>
    </div>
    <div class="ds-card">
      <span class="ds-kicker">A signal that lies</span>
      <h3>Nobody is watching</h3>
      <p class="ds-body">Deciding whether to escalate a finished long-running turn to a phone requires knowing if
        anyone is still looking. Subscriber count cannot answer it: the stream closes about ten milliseconds after a
        terminal event, so by the time the escalation grace period elapses the count is zero <b>whether or not</b>
        someone is sitting there. Presence is therefore tracked separately, on its own heartbeat with its own expiry.
        The obvious signal was not merely imprecise — it was systematically wrong at exactly the moment it was needed.</p>
    </div>
    <div class="ds-card">
      <span class="ds-kicker">Translation, in prose</span>
      <h3>Machinery, rewritten into English</h3>
      <p class="ds-body">The runtime interleaves a raw tool log into the text stream, so lines naming internal tool
        identifiers get persisted as part of the reply. A pure string transform rewrites them into sentences — eighty-eight
        tool-specific phrasings — behind two false-positive guards, because without them a genuine reply that happens
        to begin with a summary marker gets mangled into machine-speak. The guard list had to be widened once, after
        it turned out the runtime uses a different glyph per tool.</p>
    </div>
